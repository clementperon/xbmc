"""
Regenerate the symbols Kodi's wasm build exports to binary add-ons.

Binary add-ons are Emscripten side modules loaded with dlopen(). Kodi links
with -sMAIN_MODULE=2, so it exports only the symbols listed in
cmake/scripts/wasm/addon-exports*.txt, and an add-on importing anything else
fails to load. This script scans built add-ons and rewrites both lists with
the union of their imports.

Usage:
  python3 tools/wasm/addon_exports.py <add-on directory or library>...

Directories are searched recursively for side modules. Rerun it over all
built add-ons whenever add-ons or Emscripten are updated, and commit the lists.
"""

import os
import sys

# Provided by the dynamic linker rather than by Kodi.
LINKER_SYMBOLS = {
    "memory",
    "__indirect_function_table",
    "__memory_base",
    "__table_base",
    "__stack_pointer",
    "__tls_base",
}

HEADER = """\
# Symbols Kodi exports to binary add-ons (wasm side modules).
# Generated by tools/wasm/addon_exports.py from the imports of built add-ons:
# rerun it over all built add-ons to update this file.
"""


def uleb(data, pos):
    result = shift = 0
    while True:
        byte = data[pos]
        pos += 1
        result |= (byte & 0x7F) << shift
        shift += 7
        if byte < 0x80:
            return result, pos


def name(data, pos):
    length, pos = uleb(data, pos)
    return data[pos:pos + length].decode("utf-8"), pos + length


def limits(data, pos):
    flags, pos = uleb(data, pos)
    _, pos = uleb(data, pos)
    if flags & 1:
        _, pos = uleb(data, pos)
    return pos


def side_module_imports(data):
    """Return the symbols a side module needs from Kodi, or None if it is no side module."""
    if data[:4] != b"\0asm":
        return None
    pos = 8
    imports, exports = set(), set()
    first = True
    while pos < len(data):
        section_id = data[pos]
        size, pos = uleb(data, pos + 1)
        end = pos + size
        if first:
            if section_id != 0 or name(data, pos)[0] != "dylink.0":
                return None
            first = False
        if section_id == 2:
            count, p = uleb(data, pos)
            for _ in range(count):
                module, p = name(data, p)
                field, p = name(data, p)
                kind = data[p]
                p += 1
                if kind == 0:
                    _, p = uleb(data, p)
                elif kind == 1:
                    p = limits(data, p + 1)
                elif kind == 2:
                    p = limits(data, p)
                elif kind == 3:
                    p += 2
                elif kind == 4:
                    _, p = uleb(data, p + 1)
                # The dynamic linker creates the invoke_* and __cxa_find_matching_catch_*
                # helpers of JS-based exception handling on demand.
                if module in ("env", "GOT.func", "GOT.mem") and not field.startswith(
                        ("invoke_", "__cxa_find_matching_catch_")):
                    imports.add(field)
        elif section_id == 7:
            count, p = uleb(data, pos)
            for _ in range(count):
                field, p = name(data, p)
                _, p = uleb(data, p + 1)
                exports.add(field)
        pos = end
    return imports - exports - LINKER_SYMBOLS


def libraries(paths):
    for path in paths:
        if os.path.isfile(path):
            yield path
        for root, _, files in os.walk(path):
            for file in files:
                full = os.path.join(root, file)
                if not os.path.islink(full):
                    yield full


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)

    symbols = set()
    count = 0
    for path in libraries(sys.argv[1:]):
        with open(path, "rb") as f:
            needed = side_module_imports(f.read())
        if needed is not None:
            count += 1
            symbols |= needed
            print(f"{path}: {len(needed)} symbols")
    if count == 0:
        sys.exit("no side modules found")

    # libGL's wrappers proxy to the thread owning the WebGL context; they are exported from the
    # wasm, as EXPORTED_FUNCTIONS would pick Emscripten's unproxied JS implementations.
    gl = sorted(s for s in symbols if s.startswith("gl") and s[2:3].isupper())
    other = sorted(f"_{s}" for s in symbols - set(gl))

    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "cmake",
                           "scripts", "wasm")
    with open(os.path.join(out_dir, "addon-exports.txt"), "w") as f:
        f.write(HEADER + "\n".join(["_main"] + other) + "\n")
    with open(os.path.join(out_dir, "addon-exports-gl.txt"), "w") as f:
        f.write(HEADER + "\n".join(gl) + "\n")
    print(f"{count} add-on libraries: {len(other) + 1} exported functions, {len(gl)} GL functions")


if __name__ == "__main__":
    main()
